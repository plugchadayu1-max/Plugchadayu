# แปลงชีตตัวละครแบบตาราง (แถวละ 1 ท่า x 1 ทิศ) เป็น game\<key>.js  ใช้ภาพเดิมตรงๆ ไม่ตัดต่อใหม่
# ลำดับแถว: ท่าละ 4 แถว เรียง up, left, down, right  (ตาม photo\devil_girl_pixel\devil_girl_sheet.json)
# วิธีรัน:
#   powershell -ExecutionPolicy Bypass -File game\tools\build_grid.ps1 -src photo\devil_girl_pixel\devil_girl_sheet.png -key px_devil -cell 80 -anims idle,walk,attack
param([string]$src='photo\devil_girl_pixel\devil_girl_sheet.png',[string]$key='px_devil',[int]$cell=80,[string[]]$anims=@('idle','walk','attack'))
$anims = @($anims | ForEach-Object { $_ -split ',' } | Where-Object { $_ })   # -File ส่ง "a,b,c" มาเป็นข้อความเดียว
Add-Type -AssemblyName System.Drawing
$root = Split-Path (Split-Path $PSScriptRoot)
$path = Join-Path $root $src
$b = New-Object Drawing.Bitmap $path
$cols = [int]($b.Width / $cell); $rows = [int]($b.Height / $cell)
$dirs = @('back','left','front','right')   # up, left, down, right
$parts = @(); $row = 0
foreach($a in $anims){
  $d = @(); foreach($dir in $dirs){ $d += "$dir`:[" + ((0..($cols-1) | ForEach-Object { $row*$cols + $_ }) -join ',') + "]"; $row++ }
  $parts += "$a`:{" + ($d -join ',') + "}"
}
# เท้า + ความสูงลำตัว จากท่ายืนหันหน้าเฟรมแรก
$fr = [Array]::IndexOf($anims,'idle')*4 + 2; $oy = $fr*$cell; $top = 999; $bot = 0
for($y=0;$y -lt $cell;$y++){ for($x=0;$x -lt $cell;$x++){ if($b.GetPixel($x,$oy+$y).A -gt 40){ if($y -lt $top){$top=$y}; if($y -gt $bot){$bot=$y} } } }
$b.Dispose()
$ci = [Globalization.CultureInfo]::InvariantCulture
$img = [Convert]::ToBase64String([IO.File]::ReadAllBytes($path))
$js = "// generated by tools/build_grid.ps1 from $src - do not edit by hand`nwindow.SPRITES=window.SPRITES||{};window.SPRITES.$key={img:'data:image/png;base64,$img',cw:$cell,ch:$cell,cols:$cols,rows:$rows,pixel:true,foot:$((($bot+1)/$cell).ToString('0.####',$ci)),cx:0.5,body:$($bot-$top+1),anims:{$($parts -join ',')}};`n"
$out = Join-Path $root "game\$key.js"
[IO.File]::WriteAllText($out, $js, (New-Object Text.UTF8Encoding $false))
"wrote $out  body=$($bot-$top+1)px foot=$($bot+1)/$cell  $([int]($js.Length/1KB)) KB"
