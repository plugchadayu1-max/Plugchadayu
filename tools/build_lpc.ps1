# Convert an LPC (Universal LPC Spritesheet) character into game/lpc_<key>.js
# Run:
#   powershell -ExecutionPolicy Bypass -File game\tools\build_lpc.ps1 -src photo\character-spritesheet.png  -key warrior -weapon sword
#   powershell -ExecutionPolicy Bypass -File game\tools\build_lpc.ps1 -src photo\character-spritesheet1.png -key archer  -weapon bow
# LPC rows (64px): 0-3 spellcast, 4-7 thrust, 8-11 walk, 12-15 slash, 16-19 shoot, 20 hurt, 21 climb,
#   22-25 idle, 26-29 jump, 30-33 sit, 34-37 emote, 38-41 run, 42-45 combat idle, 46-49 backslash, 50-53 halfslash
# from y=3456 the sheet has 128px "oversize" blocks that depend on the weapon:
#   sword: slash (6 frames) / backslash (13) / halfslash (6)      bow: walk holding the bow (9 frames)
# direction order in every block: up, left, down, right
#   staff: the oversize section is 192px (thrust with the staff, 8 frames) - only walk/hurt/oversize rows draw the staff,
#          so idle = walk column 0 (standing) and attack = staff thrust; the atlas cell grows to 192
#   powershell -ExecutionPolicy Bypass -File game\tools\build_lpc.ps1 -src "photo\Mage character-spritesheet.png" -key mage -weapon staff
param([string]$src = 'photo\character-spritesheet.png', [string]$key = 'warrior', [ValidateSet('sword','bow','staff')][string]$weapon = 'sword')
Add-Type -AssemblyName System.Drawing
$root = Split-Path (Split-Path $PSScriptRoot)
$b = New-Object Drawing.Bitmap (Join-Path $root $src)
$CS = if($weapon -eq 'staff'){192}else{128}   # atlas cell (fits the oversize frames)
$OV = 3456                                 # y where the 128px oversize section starts
$dirs = @('back','left','front','right')   # LPC: up, left, down, right
$frames = New-Object System.Collections.ArrayList
function Add64($anim,$dir,$row,$col){ [void]$frames.Add(@{a=$anim;d=$dir;x=$col*64;y=$row*64;s=64}) }
function Add128($anim,$dir,$y0,$i,$col){ [void]$frames.Add(@{a=$anim;d=$dir;x=$col*128;y=$y0+$i*128;s=128}) }
function Add192($anim,$dir,$y0,$i,$col){ [void]$frames.Add(@{a=$anim;d=$dir;x=$col*192;y=$y0+$i*192;s=192}) }
for($i=0;$i -lt 4;$i++){
  if($weapon -eq 'sword'){
    foreach($k in 0..1){ Add64 'idle' $dirs[$i] (22+$i) $k }
    foreach($k in 1..8){ Add64 'walk' $dirs[$i] (8+$i) $k }
    foreach($k in 0..5){ Add128 'attack' $dirs[$i] $OV $i $k }       # big slash with the sword arc
  } elseif($weapon -eq 'staff'){
    Add64 'idle' $dirs[$i] (8+$i) 0                                   # standing, holding the staff
    foreach($k in 1..8){ Add64 'walk' $dirs[$i] (8+$i) $k }
    foreach($k in 0..7){ Add192 'attack' $dirs[$i] $OV $i $k }        # thrust the staff forward
  } else {
    Add128 'idle' $dirs[$i] $OV $i 0                                  # standing, holding the bow
    foreach($k in 1..8){ Add128 'walk' $dirs[$i] $OV $i $k }          # walking, holding the bow
    foreach($k in 0..12){ Add64 'attack' $dirs[$i] (16+$i) $k }       # draw + shoot
  }
}
foreach($k in 0..2){ Add64 'hurt' 'all' 20 $k }
foreach($k in 0..5){ Add64 'death' 'all' 20 $k }
$cols = 12; $rows = [Math]::Ceiling($frames.Count / $cols)
$atlas = New-Object Drawing.Bitmap ($cols*$CS), ($rows*$CS), ([Drawing.Imaging.PixelFormat]::Format32bppArgb)
$g = [Drawing.Graphics]::FromImage($atlas); $g.InterpolationMode = 'NearestNeighbor'; $g.PixelOffsetMode = 'Half'
$anims = [ordered]@{}
for($i=0;$i -lt $frames.Count;$i++){
  $f = $frames[$i]; $ox = ($i % $cols)*$CS; $oy = [Math]::Floor($i / $cols)*$CS
  $off = ($CS - $f.s)/2                   # smaller frames sit in the middle of the cell (same as LPC oversize layout)
  $g.DrawImage($b, (New-Object Drawing.Rectangle ($ox+$off),($oy+$off),$f.s,$f.s), (New-Object Drawing.Rectangle $f.x,$f.y,$f.s,$f.s), [Drawing.GraphicsUnit]::Pixel)
  if(-not $anims[$f.a]){ $anims[$f.a] = [ordered]@{} }; if(-not $anims[$f.a][$f.d]){ $anims[$f.a][$f.d] = New-Object System.Collections.ArrayList }
  [void]$anims[$f.a][$f.d].Add($i)
}
$g.Dispose()
# feet + body height from the first idle-front frame
$fi = $anims['idle']['front'][0]; $fx = ($fi % $cols)*$CS; $fy = [Math]::Floor($fi / $cols)*$CS
$top = 999; $bot = 0
for($y=0;$y -lt $CS;$y++){ for($x=0;$x -lt $CS;$x++){ if($atlas.GetPixel($fx+$x,$fy+$y).A -gt 40){ if($y -lt $top){$top=$y}; if($y -gt $bot){$bot=$y} } } }
$ms = New-Object IO.MemoryStream; $atlas.Save($ms,[Drawing.Imaging.ImageFormat]::Png)
$ci = [Globalization.CultureInfo]::InvariantCulture
$animJs = ($anims.Keys | ForEach-Object { $a=$_; "$a`:{" + (($anims[$a].Keys | ForEach-Object { "$_`:[" + ($anims[$a][$_] -join ',') + "]" }) -join ',') + "}" }) -join ','
$sheet = "lpc_$key"
$js = "// generated by tools/build_lpc.ps1 from $src - do not edit by hand`nwindow.SPRITES=window.SPRITES||{};window.SPRITES.$sheet={img:'data:image/png;base64,$([Convert]::ToBase64String($ms.ToArray()))',cw:$CS,ch:$CS,cols:$cols,rows:$rows,pixel:true,foot:$((($bot+1)/$CS).ToString('0.####',$ci)),cx:0.5,body:$($bot-$top+1),anims:{$animJs}};`n"
$out = Join-Path $root "game\$sheet.js"
[IO.File]::WriteAllText($out, $js, (New-Object Text.UTF8Encoding $false))
"wrote $out  frames=$($frames.Count)  body=$($bot-$top+1)px  foot=$($bot+1)/$CS  $([int]($js.Length/1KB)) KB"
$atlas.Save((Join-Path $env:TEMP "$sheet`_preview.png"))
