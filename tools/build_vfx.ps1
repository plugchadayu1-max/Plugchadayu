# Pack skill VFX frames (SKill folder) into game/vfx.js as horizontal strips (base64 PNG)
# Run:  powershell -ExecutionPolicy Bypass -File game\tools\build_vfx.ps1
Add-Type -AssemblyName System.Drawing
$root = Split-Path (Split-Path $PSScriptRoot)
$S = Join-Path $root 'SKill'
$W = Join-Path $S 'Pixel Art Animations - Warrior (FREE)'
$Lt = Join-Path $S 'Pixel Art Skill Animations - Lightning'
$sets = [ordered]@{
  frost = (Get-ChildItem $S -Recurse -Directory -Filter 'Frost Mage VFX4' | Select-Object -First 1).FullName + '\Frames'
  war1 = "$W\VFX 1\Frames"; war2 = "$W\VFX 2\Frames"; war3 = "$W\VFX 3\Frames"; war4 = "$W\VFX 4\Frames"; war5 = "$W\VFX 5\Frames"
  lit1 = "$Lt\VFX1\Frames"; lit2 = "$Lt\VFX2\Frames"; lit3 = "$Lt\VFX3\Frames"; lit4 = "$Lt\VFX4\Frames"; lit5 = "$Lt\VFX5\Frames"; lit6 = "$Lt\VFX6\Frames"
}
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('// generated by tools/build_vfx.ps1 - do not edit by hand')
[void]$sb.Append('window.VFX={')
foreach ($k in $sets.Keys) {
  $files = Get-ChildItem $sets[$k] -Filter *.png | Sort-Object { [int]([regex]::Match($_.Name, '(\d+)\.png$').Groups[1].Value) }
  $first = [Drawing.Image]::FromFile($files[0].FullName); $fw = $first.Width; $fh = $first.Height; $first.Dispose()
  $strip = New-Object Drawing.Bitmap ($fw * $files.Count), $fh, ([Drawing.Imaging.PixelFormat]::Format32bppArgb)
  $g = [Drawing.Graphics]::FromImage($strip); $g.InterpolationMode = 'NearestNeighbor'
  $i = 0; foreach ($f in $files) { $im = [Drawing.Image]::FromFile($f.FullName); $g.DrawImage($im, (New-Object Drawing.Rectangle ($i * $fw), 0, $fw, $fh)); $im.Dispose(); $i++ }
  $g.Dispose(); $ms = New-Object IO.MemoryStream; $strip.Save($ms, [Drawing.Imaging.ImageFormat]::Png); $strip.Dispose()
  [void]$sb.Append("$k`:{img:'data:image/png;base64,$([Convert]::ToBase64String($ms.ToArray()))',fw:$fw,fh:$fh,n:$($files.Count)},")
  "$k : $($files.Count) frames ${fw}x${fh}"
}
[void]$sb.AppendLine('};')
$out = Join-Path $root 'game\vfx.js'
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding $false))
"wrote $out $([int]((Get-Item $out).Length/1KB)) KB"
