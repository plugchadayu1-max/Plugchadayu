# Bundle KayKit models (.glb/.gltf) into tools/models.js, used by tools/bake.html
# (bake.html renders the 3D models into 2D sprite sheets -> game/kaykit_sprites.js)
# Run:  powershell -ExecutionPolicy Bypass -File game\tools\build_models.ps1
$root = Split-Path (Split-Path $PSScriptRoot)          # D:\2.SCHOOL\start 011069
$A = Join-Path $root 'photo\KayKit_Adventurers_2.0_FREE\KayKit_Adventurers_2.0_FREE'
$K = Join-Path $root 'photo\KayKit_Skeletons_1.1_FREE\KayKit_Skeletons_1.1_FREE'
$out = Join-Path $root 'game\tools\models.js'

$glb = [ordered]@{
  Knight           = "$A\Characters\gltf\Knight.glb"
  Mage             = "$A\Characters\gltf\Mage.glb"
  Ranger           = "$A\Characters\gltf\Ranger.glb"
  Rogue            = "$A\Characters\gltf\Rogue.glb"
  Skeleton_Minion  = "$K\characters\gltf\Skeleton_Minion.glb"
  Skeleton_Rogue   = "$K\characters\gltf\Skeleton_Rogue.glb"
  Skeleton_Mage    = "$K\characters\gltf\Skeleton_Mage.glb"
  Skeleton_Warrior = "$K\characters\gltf\Skeleton_Warrior.glb"
  Anim_General     = "$A\Animations\gltf\Rig_Medium\Rig_Medium_General.glb"
  Anim_Move        = "$A\Animations\gltf\Rig_Medium\Rig_Medium_MovementBasic.glb"
}
$gltf = [ordered]@{
  sword_1handed      = "$A\Assets\gltf\sword_1handed.gltf"
  shield_badge_color = "$A\Assets\gltf\shield_badge_color.gltf"
  staff              = "$A\Assets\gltf\staff.gltf"
  bow_withString     = "$A\Assets\gltf\bow_withString.gltf"
  dagger             = "$A\Assets\gltf\dagger.gltf"
  Skeleton_Blade     = "$K\assets\gltf\Skeleton_Blade.gltf"
  Skeleton_Axe       = "$K\assets\gltf\Skeleton_Axe.gltf"
  Skeleton_Staff     = "$K\assets\gltf\Skeleton_Staff.gltf"
  Skeleton_Shield_Large_A = "$K\assets\gltf\Skeleton_Shield_Large_A.gltf"
  Skeleton_Shield_Small_A = "$K\assets\gltf\Skeleton_Shield_Small_A.gltf"
}

$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('// generated by tools/build_models.ps1 - do not edit by hand')
[void]$sb.AppendLine('window.KAYKIT_GLB={')
foreach ($k in $glb.Keys) {
  $b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($glb[$k]))
  [void]$sb.AppendLine("$k`:'$b64',")
}
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('window.KAYKIT_GLTF={')
foreach ($k in $gltf.Keys) {
  $p = $gltf[$k]; $dir = Split-Path $p
  $j = Get-Content $p -Raw | ConvertFrom-Json
  foreach ($b in $j.buffers) { $b.uri = 'data:application/octet-stream;base64,' + [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $dir $b.uri))) }
  foreach ($im in $j.images) { if ($im.uri) { $im.uri = 'data:image/png;base64,' + [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $dir $im.uri))) } }
  $txt = ($j | ConvertTo-Json -Depth 50 -Compress) -replace "'", "\'"
  [void]$sb.AppendLine("$k`:'$txt',")
}
[void]$sb.AppendLine('};')
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding $false))
"wrote $out  $([int]((Get-Item $out).Length/1KB)) KB"
